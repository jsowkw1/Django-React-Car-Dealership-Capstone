"""Runs every documented cURL command against the running app and writes the REAL outputs
to submission/CURL_COMMANDS.md. Requires curl, Express on :3030 and Django on :8000.

    python scripts/run_curl_examples.py
"""
import os
import shlex
import subprocess
import tempfile
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
API = os.getenv('API_URL', 'http://localhost:3030')
WEB = os.getenv('WEB_URL', 'http://localhost:8000')
USER = os.getenv('DEMO_USERNAME', 'jsowkw1')
PASSWORD = os.getenv('DEMO_PASSWORD', 'DriveSafe#2026')
JAR = Path(tempfile.gettempdir()) / 'capstone-curl-cookies.txt'
MAX_LINES = 40

out = []


seen_tokens = set()


def csrf_token():
    for line in JAR.read_text().splitlines():
        parts = line.split('\t')
        if len(parts) == 7 and parts[5] == 'csrftoken':
            seen_tokens.add(parts[6])
            return parts[6]
    return ''


def run(title, args, note=''):
    """args: list of curl arguments (without the leading 'curl')."""
    cmd = ['curl', '-s', '-w', '\\nHTTP status: %{http_code}\\n'] + args
    result = subprocess.run(cmd, capture_output=True, text=True, encoding='utf-8')
    body = result.stdout.strip()
    lines = body.splitlines()
    if len(lines) > MAX_LINES:
        lines = lines[:MAX_LINES - 2] + [f'... ({len(lines) - MAX_LINES + 2} more lines omitted for brevity)', lines[-1]]
    shown = ' '.join(shlex.quote(a) for a in ['curl', '-s'] + args)
    out.append(f'### {title}\n')
    if note:
        out.append(f'{note}\n')
    out.append(f'```bash\n{shown}\n```\n')
    out.append('ACTUAL OUTPUT:\n')
    out.append(f'```json\n' + '\n'.join(lines) + '\n```\n')
    print(title, '->', lines[-1] if lines else '(no output)')


def main():
    JAR.unlink(missing_ok=True)
    out.append('# cURL commands and actual outputs\n')
    out.append(
        f'Generated by `scripts/run_curl_examples.py` on {datetime.now(timezone.utc):%Y-%m-%d %H:%M UTC} against the '
        f'locally running application (Express API `{API}`, Django `{WEB}`). Every output below is the real '
        'response captured from that run; long lists are shortened and marked as such.\n'
    )

    out.append('## Express + MongoDB API (port 3030)\n')
    run('1. Retrieve all dealers', [f'{API}/fetchDealers'])
    run('2. Retrieve dealer by ID', [f'{API}/fetchDealer/3'])
    run('3. Retrieve dealers by state (Kansas)', [f'{API}/fetchDealers/Kansas'])
    run('3b. Retrieve dealers by state code (case-insensitive)', [f'{API}/fetchDealers/ks'])
    run('4. Retrieve reviews by dealer ID', [f'{API}/fetchReviews/dealer/1'])
    run('7. Analyze review sentiment — required test phrase "Fantastic services"',
        [f'{API}/analyze/Fantastic%20services'])
    run('7b. Analyze sentiment (POST, negative text)',
        ['-X', 'POST', f'{API}/analyze', '-H', 'Content-Type: application/json',
         '-d', '{"text": "Rude staff and hidden fees, a terrible experience"}'])
    run('8. Insert a review directly (201 Created)',
        ['-X', 'POST', f'{API}/insert_review', '-H', 'Content-Type: application/json', '-d',
         '{"name": "cURL Tester", "dealership": 5, "review": "Great prices and friendly staff", "rating": 5, '
         '"purchase": true, "purchase_date": "2026-09-30", "car_make": "Ford", "car_model": "F-150", "car_year": 2025}'],
        note='In production `API_KEY` is set and this call additionally needs `-H "X-API-Key: <key>"` (otherwise 401).')

    out.append('## Error handling examples\n')
    run('400 Bad Request — invalid dealer id', [f'{API}/fetchDealer/abc'])
    run('404 Not Found — unknown dealer', [f'{API}/fetchDealer/999'])
    run('400 Bad Request — invalid review payload',
        ['-X', 'POST', f'{API}/insert_review', '-H', 'Content-Type: application/json', '-d', '{"dealership": 1, "rating": 9}'])
    run('404 Not Found — unknown route', [f'{API}/doesNotExist'])

    out.append('## Django application API (port 8000)\n')
    run('5. Retrieve all car makes', [f'{WEB}/djangoapp/get_car_makes'])
    run('6. Retrieve car models (all, course format)', [f'{WEB}/djangoapp/get_cars'])
    run('6b. Retrieve car models filtered by make', [f'{WEB}/djangoapp/get_car_models?make=Toyota'])
    run('Dealers through Django (proxied to Express)', [f'{WEB}/djangoapp/get_dealers/Kansas'])
    run('Dealer details through Django', [f'{WEB}/djangoapp/dealer/1'])
    run('Dealer reviews with sentiment and average rating', [f'{WEB}/djangoapp/reviews/dealer/1'])
    run('Sentiment analyzer through Django', [f'{WEB}/djangoapp/analyze/Fantastic%20services'])

    out.append('### Authentication flow with session cookies and CSRF\n')
    run('Get a CSRF cookie (current user = anonymous)', ['-c', str(JAR), f'{WEB}/djangoapp/me'])
    token = csrf_token()
    auth = ['-b', str(JAR), '-c', str(JAR), '-H', 'Content-Type: application/json', '-H', f'X-CSRFToken: {token}']
    run('401 Unauthorized — post a review without logging in',
        ['-X', 'POST', f'{WEB}/djangoapp/add_review'] + auth + ['-d', '{"dealership": 1, "review": "Nice", "rating": 4}'])
    run('401 Unauthorized — wrong password',
        ['-X', 'POST', f'{WEB}/djangoapp/login'] + auth + ['-d', f'{{"userName": "{USER}", "password": "wrong"}}'])
    run('200 OK — login',
        ['-X', 'POST', f'{WEB}/djangoapp/login'] + auth + ['-d', f'{{"userName": "{USER}", "password": "<password>"}}'.replace('<password>', PASSWORD)],
        note='Uses the documented demonstration account.')
    token = csrf_token()  # Django rotates the CSRF token on login
    auth[-1] = f'X-CSRFToken: {token}'
    run('201 Created — post a review as the logged-in user',
        ['-X', 'POST', f'{WEB}/djangoapp/add_review'] + auth +
        ['-d', '{"dealership": 2, "review": "Fantastic services and a fair trade-in offer", "rating": 5, '
               '"purchase": true, "purchase_date": "2026-10-20", "car_make": "Ford", "car_model": "F-150", "car_year": 2025}'])
    run('400 Bad Request — registration validation',
        ['-X', 'POST', f'{WEB}/djangoapp/register'] + auth +
        ['-d', f'{{"userName": "{USER}", "firstName": "", "lastName": "", "email": "bad", "password": "123"}}'])
    run('200 OK — logout', ['-X', 'POST', f'{WEB}/djangoapp/logout'] + auth)

    text = '\n'.join(out).replace(PASSWORD, '<demo-password>').replace(str(JAR), 'cookies.txt')
    for t in seen_tokens:
        text = text.replace(t, '<csrftoken from cookies.txt>')
    (ROOT / 'submission' / 'CURL_COMMANDS.md').write_text(text, encoding='utf-8')
    JAR.unlink(missing_ok=True)
    print('wrote submission/CURL_COMMANDS.md')


if __name__ == '__main__':
    main()
